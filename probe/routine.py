def _model(label: str) -> dict[str, Any]:
    for m in MODELS:
        if m["label"] == label:
            return m
    raise KeyError(label)


def lane_targets(lister=openrouter.list_endpoints, hosts: int = 2, outside: bool = True,
                 routes_dir: Path = ROUTES_DIR) -> list[dict[str, Any]]:
    """Cheapest `hosts` allowed endpoints per lane model, plus the cheapest excluded-as-outside one.

    Only endpoints OpenRouter lists right now with a price are used. The route list is already
    ordered cheapest first by blended price.
    """
    out: list[dict[str, Any]] = []
    for label in LANE_LABELS:
        slug = _model(label)["slug"]
        path = routes_dir / f"{slug}.json"
        if not path.exists():
            continue
        route = json.loads(path.read_text(encoding="utf-8"))
        live = {e["tag"]: e for e in lister(slug) if e.get("price_in")}
        picked = [t for t in route.get("allow", []) if t in live][:hosts]
        for tag in picked:
            out.append({"kind": "lane", "label": label, "slug": slug, "tag": tag, "as_of": route.get("as_of"), **_ep(live[tag])})
        if outside:
            ex = [e["tag"] for e in route.get("excluded", []) if e.get("why") == "outside" and e["tag"] in live]
            ex.sort(key=lambda t: 3 * live[t]["price_in"] + live[t]["price_out"])
            for tag in ex[:1]:
                out.append({"kind": "outside", "label": label, "slug": slug, "tag": tag, "as_of": route.get("as_of"), **_ep(live[tag])})
    return out


def _ep(e: dict[str, Any]) -> dict[str, Any]:
    return {"provider_name": e.get("provider_name"), "price_in": float(e["price_in"]), "price_out": float(e["price_out"]),
            "quantization": e.get("quantization", "unknown")}


def resolve_baseline(requested: str, models: list[dict[str, Any]]) -> dict[str, Any] | None:
    """The requested slug if OpenRouter lists it, else the newest slug under BASELINE_PREFIX."""
    by_id = {m.get("id"): m for m in models}
    m = by_id.get(requested)
    resolved_from = None
    if m is None:
        cands = [x for x in models if str(x.get("id", "")).startswith(BASELINE_PREFIX) and ":" not in str(x.get("id"))]
        if not cands:
            return None
        m = max(cands, key=lambda x: x.get("created") or 0)
        resolved_from = requested
    pricing = m.get("pricing") or {}
    return {"kind": "baseline", "label": m["id"].split("/")[-1], "slug": m["id"], "tag": None, "provider_name": None,
            "price_in": float(pricing.get("prompt") or 0.0), "price_out": float(pricing.get("completion") or 0.0),
            "quantization": "n/a", "resolved_from": resolved_from}


