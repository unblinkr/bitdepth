def _group(row: dict[str, Any]) -> str:
    return "baseline" if row["kind"] == "baseline" else f"{row['kind']}:{row['model']}"


def _cached(usage: dict[str, Any]) -> int:
    d = usage.get("prompt_tokens_details") or {}
    return int(d.get("cached_tokens") or 0)


def summarise(rows: list[dict[str, Any]]) -> dict[str, Any]:
    """Per job and group: calls that returned, passes, mean billed cost and the monthly figure."""
    cells: dict[str, dict[str, dict[str, Any]]] = {}
    for job in JOBS:
        cells[job] = {}
        for g in sorted({_group(r) for r in rows}):
            rs = [r for r in rows if r["job"] == job and _group(r) == g]
            ok = [r for r in rs if r["status"] == "ok"]
            mean_cost = sum(r["cost_usd"] for r in ok) / len(ok) if ok else None
            cells[job][g] = {
                "sent": len([r for r in rs if r["status"] != "skipped_budget"]),
                "ok": len(ok),
                "passed": sum(1 for r in ok if r["passed"]),
                "pass_rate": round(sum(1 for r in ok if r["passed"]) / len(ok), 4) if ok else None,
                "mean_cost_usd": round(mean_cost, 6) if mean_cost is not None else None,
                "mean_prompt_tokens": round(sum((r["usage"].get("prompt_tokens") or 0) for r in ok) / len(ok)) if ok else None,
                "mean_cached_tokens": round(sum(_cached(r["usage"]) for r in ok) / len(ok)) if ok else None,
                "monthly_usd": round(mean_cost * CALLS_PER_MONTH[job], 2) if mean_cost is not None else None,
            }
    groups = sorted({g for job in cells.values() for g in job})
    totals = {}
    for g in groups:
        vals = [cells[j][g]["monthly_usd"] for j in JOBS if g in cells[j]]
        totals[g] = round(sum(vals), 2) if vals and all(v is not None for v in vals) else None
    return {"jobs": cells, "groups": groups, "monthly_total_usd": totals}


def _money(v: float | None) -> str:
    return "n/a" if v is None else f"${v:,.2f}"


def _rate(c: dict[str, Any]) -> str:
    return "n/a" if not c or not c["ok"] else f"{c['passed']}/{c['ok']}"


def report_md(record: dict[str, Any], summary: dict[str, Any], rows: list[dict[str, Any]]) -> str:
    groups = summary["groups"]
    lines = [
        f"# Routine jobs: cost and pass rate, {record['date']}",
        "",
        "One-off measurement. Working data, not a finding. Numbers against stated answers; nothing here says why an endpoint answers as it does.",
        "",
        f"- Baseline: `{record['baseline']['slug']}` on default routing" +
        (f" (requested `{record['baseline']['resolved_from']}`, not listed)" if record["baseline"].get("resolved_from") else ""),
        f"- Lane: the cheapest {record['lane_hosts']} allowed endpoints on the route list as of {record.get('route_as_of')}, per model",
        "- Outside: the cheapest endpoint the route list excludes as outside, where OpenRouter still lists one",
        f"- System prompt: {record['overhead_chars']} characters (about {record['overhead_chars'] // 4} tokens), the same on every call",
        f"- Instances per job: {record['instances']}. Temperature 0, reasoning off where the endpoint allows it.",
        f"- Billed: ${record['total_billed_usd']:.4f} of a ${record['cap_usd']:.2f} cap. Rows skipped for budget: {record['skipped_budget']}.",
        "",
        "## Monthly cost at the stated schedule, and passes",
        "",
        "Passes are instances answered correctly over instances that returned.",
        "",
        "| Job | Calls a month | " + " | ".join(groups) + " |",
        "| --- | --- | " + " | ".join("---" for _ in groups) + " |",
    ]
    for job in JOBS:
        cells = summary["jobs"][job]
        lines.append(f"| {job} | {CALLS_PER_MONTH[job]:,} | " + " | ".join(
            f"{_money(cells.get(g, {}).get('monthly_usd'))} ({_rate(cells.get(g, {}))})" for g in groups) + " |")
    lines.append("| **Total** | | " + " | ".join(_money(summary["monthly_total_usd"].get(g)) for g in groups) + " |")
    base = summary["monthly_total_usd"].get("baseline")
    lines += ["", "## Saving against the baseline", ""]
    for g in groups:
        if not g.startswith("lane:"):
            continue
        tot = summary["monthly_total_usd"].get(g)
        passed = sum(summary["jobs"][j][g]["passed"] for j in JOBS if g in summary["jobs"][j])
        ok = sum(summary["jobs"][j][g]["ok"] for j in JOBS if g in summary["jobs"][j])
        if base and tot is not None:
            lines.append(f"- {g}: {_money(tot)} a month against {_money(base)}, {100 * (1 - tot / base):.1f}% lower. Passes: {passed}/{ok}.")
        else:
            lines.append(f"- {g}: {_money(tot)} a month. Baseline not available. Passes: {passed}/{ok}.")
    lines += ["", "## Per endpoint", "", "| Kind | Model | Endpoint | Returned | Passed | Mean cost per call |", "| --- | --- | --- | --- | --- | --- |"]
    keys = sorted({(r["kind"], r["model"], r["pinned_tag"] or "default routing") for r in rows})
    for kind, model, tag in keys:
        rs = [r for r in rows if r["kind"] == kind and r["model"] == model and (r["pinned_tag"] or "default routing") == tag]
        ok = [r for r in rs if r["status"] == "ok"]
        mc = sum(r["cost_usd"] for r in ok) / len(ok) if ok else None
        lines.append(f"| {kind} | {model} | {tag} | {len(ok)}/{len(rs)} | {sum(1 for r in ok if r['passed'])} | "
                     + ("n/a" if mc is None else f"${mc:.5f}") + " |")
    lines += [
        "",
        "## Schedule assumptions",
        "",
        "Heartbeat every 30 minutes; monitor every 15 minutes; a daily digest of 5 model calls; "
        "a daily briefing of 10 model calls; 50 tagging batches of 20 tickets a day. "
        "Each measured call stands for one model call in that schedule.",
        "",
        "## Limits",
        "",
        f"- {record['instances']} instances per job is a small sample. Treat a pass rate as a first read.",
        "- The jobs are synthetic and short. A real agent's jobs call tools and carry longer histories.",
        "- Prompt caching is whatever each endpoint applied by default; cached tokens are in the rows.",
        "",
        "Numbers against a stated reference. Not a claim about intent.",
        "",
    ]
    return "\n".join(lines)


