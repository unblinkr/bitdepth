"""One-off measurement: what routine agent jobs cost on a frontier model against the route list.

    python -m probe.routine --date YYYY-MM-DD [--dry-run] [--source dispatch|local]
        [--baseline SLUG] [--cap 3.00] [--instances 5] [--lane-hosts 2] [--no-outside]

Five synthetic jobs an always-on agent runs on a schedule (heartbeat, monitor, inbox digest,
research briefing, ticket tagging), each with an answer a string or number comparison can
check. Every job is sent with a fixed system prompt sized like an agent's bootstrap (about
13,900 tokens) to:

  baseline  one frontier model on OpenRouter's default routing
  lane      the cheapest endpoints on tonight's route list, for the open-weight models in LANE_LABELS
  outside   the cheapest endpoint the route list excludes as outside, where one is listed

The report gives the pass rate and the billed cost per call for each, and a monthly figure
from a stated schedule. Jobs and answers are generated by code from a seed. Nothing here is
taken from a public benchmark, and no model output is executed.

Spend is capped in code: the lower of --cap, $5.00, and what is left of the nightly cap after
the night's recorded run. A request is only sent when its worst case fits under the cap.
"""

