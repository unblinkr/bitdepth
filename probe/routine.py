def _ids(line: str) -> list[str]:
    return [f"{a}-{b}" for a, b in re.findall(r"\b([A-Z])-(\d+)\b", line)]


def _fmt_ids(ids: list[str]) -> str:
    return ",".join(sorted(ids, key=lambda s: int(s.split("-")[1]))) if ids else "NONE"


def _clock(minutes: int) -> str:
    return f"{minutes // 60:02d}:{minutes % 60:02d}"


_TASK_WORDS = ["renew the domain", "send the weekly note", "check the backup", "pay the contractor", "book the room",
               "file the receipt", "review the draft", "call the supplier", "update the roadmap", "rotate the key",
               "post the update", "order supplies", "confirm the meeting", "close the ticket"]


def job_heartbeat(i: int) -> dict[str, Any]:
    rng = _rng("heartbeat", i)
    now = rng.randrange(9 * 60, 20 * 60)
    n_due = (2, 0, 3)[i % 3]
    nums = rng.sample(range(1000, 9999), 14)
    words = rng.sample(_TASK_WORDS, 14)
    rows, due = [], []
    for k, num in enumerate(nums):
        tid = f"T-{num}"
        if k < n_due:
            t, status = max(0, now - rng.randrange(1, 120)), "pending"
            due.append(tid)
        elif k < n_due + 4:
            t, status = min(1439, now + rng.randrange(10, 600)), "pending"
        elif k < n_due + 8:
            t, status = max(0, now - rng.randrange(1, 600)), rng.choice(["done", "cancelled", "snoozed"])
        else:
            t, status = min(1439, now + rng.randrange(10, 600)), rng.choice(["done", "pending", "snoozed"])
        rows.append(f"{tid} | due {_clock(t)} | {status} | {words[k]}")
    rng.shuffle(rows)
    user = (
        "JOB heartbeat\n"
        f"The current time is {_clock(now)}. All times are today.\n"
        "A task is due when its status is pending and its due time is at or before the current time. "
        "Tasks that are done, cancelled or snoozed are never due.\n\n"
        "Task queue:\n" + "\n".join(rows) + "\n\n"
        "Reply with one line: DUE: followed by the due task IDs separated by commas, or DUE: NONE."
    )
    return {"job": "heartbeat", "user": user, "expect": {"DUE": sorted(due)}}


def job_monitor(i: int) -> dict[str, Any]:
    rng = _rng("monitor", i)
    n_up = (3, 0, 5)[i % 3]
    nums = rng.sample(range(100, 999), 30)
    kinds = ["up"] * n_up + ["down"] * 3 + ["flat"] * (30 - n_up - 3)
    rng.shuffle(kinds)
    rows, flagged = [], []
    for num, kind in zip(nums, kinds):
        sid = f"S-{num}"
        y = rng.randrange(80, 900)
        if kind == "up":
            t = int(y * rng.uniform(1.9, 3.0))
            flagged.append(sid)
        elif kind == "down":
            t = int(y * rng.uniform(0.4, 0.6))
        else:
            t = int(y * rng.uniform(0.92, 1.08))
        rows.append(f"{sid} | yesterday {y} ms | today {t} ms")
    user = (
        "JOB monitor\n"
        "Flag a service when today's latency is at least 1.5 times yesterday's. "
        "A service that got faster or stayed about the same is not flagged.\n\n"
        "Latency table:\n" + "\n".join(rows) + "\n\n"
        "Reply with one line: FLAGGED: followed by the flagged service IDs separated by commas, or FLAGGED: NONE."
    )
    return {"job": "monitor", "user": user, "expect": {"FLAGGED": sorted(flagged)}}


