class HardCap:
    """Spend cap with reservations: a request is sent only if its worst case fits."""

    def __init__(self, cap: float) -> None:
        self.cap = cap
        self.spent = 0.0
        self.reserved = 0.0
        self._lock = threading.Lock()

    def reserve(self, usd: float) -> bool:
        with self._lock:
            if self.spent + self.reserved + usd > self.cap:
                return False
            self.reserved += usd
            return True

    def settle(self, reserved: float, actual: float) -> None:
        with self._lock:
            self.reserved = max(0.0, self.reserved - reserved)
            self.spent += actual


def night_billed(date: str, runs_dir: Path = RUNS_DIR) -> float:
    p = runs_dir / date / "run.json"
    if not p.exists():
        return 0.0
    try:
        rec = json.loads(p.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return 0.0
    return float(rec.get("total_billed_usd") or (rec.get("summary") or {}).get("billed_cost_usd") or 0.0)


def effective_cap(requested: float, billed_tonight: float) -> float:
    return round(max(0.0, min(requested, HARD_CEILING, BUDGET_USD - billed_tonight)), 4)


def call_estimate(system: str, job: dict[str, Any], target: dict[str, Any]) -> tuple[float, float]:
    """(expected, worst case) USD for one call."""
    tin = budget.input_tokens(system + job["user"])
    expected = tin * target["price_in"] + job["max_tokens"] * target["price_out"]
    worst = tin * RESERVE_MARGIN * target["price_in"] + job["max_tokens"] * target["price_out"]
    return expected, worst


# ---------------------------------------------------------------------------
# Run
# ---------------------------------------------------------------------------

def send_all(run_id: str, system: str, jobs: list[dict[str, Any]], targets: list[dict[str, Any]], cap: HardCap,
             out_path: Path, completer=openrouter.complete) -> list[dict[str, Any]]:
    work_items = [(j, t) for j in jobs for t in targets]
    rows: list[dict[str, Any]] = []
    lock = threading.Lock()
    out_path.parent.mkdir(parents=True, exist_ok=True)

    def work(item: tuple[dict[str, Any], dict[str, Any]]) -> dict[str, Any]:
        job, t = item
        _, worst = call_estimate(system, job, t)
        row: dict[str, Any] = {
            "run_id": run_id, "ts": now_iso(), "job": job["job"], "job_id": job["id"], "instance": job["instance"],
            "kind": t["kind"], "model": t["label"], "slug": t["slug"], "pinned_tag": t["tag"],
        }
        if not cap.reserve(worst):
            row.update({"status": "skipped_budget", "output": "", "usage": {}, "cost_usd": 0.0, "cost_source": "none",
                        "passed": False, "score": 0.0, "detail": "runtime budget stop", "returned_provider": None,
                        "latency_ms": 0, "finish_reason": None, "error": "runtime budget stop"})
        else:
            result = completer(
                t["slug"], t["tag"],
                [{"role": "system", "content": system}, {"role": "user", "content": job["user"]}],
                {"max_tokens": job["max_tokens"]},
            )
            cost, source = run_mod.row_cost(result, t)
            cap.settle(worst, cost)
            status = result["status"]
            returned = result.get("provider")
            if status == "ok" and t["tag"] and returned and run_mod._norm(returned) != run_mod._norm(t["provider_name"]):
                status = "misrouted"
            g = grade(job, result.get("text") or "") if status == "ok" else {"passed": False, "score": 0.0, "detail": status}
            row.update({"status": status, "output": result.get("text") or "", "usage": result.get("usage") or {},
                        "cost_usd": round(cost, 6), "cost_source": source, "returned_provider": returned,
                        "latency_ms": result.get("latency_ms"), "finish_reason": result.get("finish_reason"),
                        "error": result.get("error") or "", **g})
        with lock:
            rows.append(row)
            with out_path.open("a", encoding="utf-8") as f:
                f.write(json.dumps(row, ensure_ascii=False) + "\n")
        return row

    with ThreadPoolExecutor(max_workers=min(MAX_WORKERS, run_mod.concurrency())) as ex:
        for fut in as_completed([ex.submit(work, it) for it in work_items]):
            fut.result()
    return rows


