def overhead() -> str:
    """Deterministic system prompt of about OVERHEAD_TOKENS (measured as characters / 4)."""
    rng = _rng("overhead")
    parts = [
        "You are an always-on assistant agent. You run on a schedule and on request. "
        "You have tools, a memory file and a list of scheduled jobs. Use a tool only when a job needs it. "
        "The tool definitions and memory notes below are loaded on every run.\n\n## Tools\n"
    ]
    target = OVERHEAD_TOKENS * 4
    seen: set[str] = set()
    while sum(len(p) for p in parts) < target * 0.86:
        name = f"{rng.choice(_VERBS)}_{rng.choice(_NOUNS)}"
        if name in seen:
            name = f"{name}_{len(seen)}"
        seen.add(name)
        props = {}
        for p in rng.sample(_PARAMS, rng.randrange(3, 7)):
            props[p] = {"type": rng.choice(_TYPES),
                        "description": f"The {p.replace('_', ' ')} to use when the tool runs. Optional unless the job states it."}
        tool = {
            "name": name,
            "description": f"Use this tool to {name.replace('_', ' ')}. Returns a JSON object with the result and a status field. "
                           "Call it at most once per step and wait for the result before the next call.",
            "parameters": {"type": "object", "properties": props, "required": sorted(props)[:1]},
        }
        parts.append(json.dumps(tool, indent=1) + "\n")
    parts.append("\n## Memory\n")
    k = 0
    while sum(len(p) for p in parts) < target:
        k += 1
        parts.append(f"Note {k}: the user {rng.choice(_HABITS)}.\n")
    parts.append(
        "\n## Scheduled jobs\nWhen a message starts with JOB, it is a scheduled job. "
        "Reply with only the answer lines the job asks for, in the exact format it gives. "
        "No other text, no explanation, no formatting marks."
    )
    return "".join(parts)


