# Entry point
# ---------------------------------------------------------------------------

def main(argv: list[str] | None = None, lister=openrouter.list_endpoints, model_lister=openrouter.list_models,
         completer=openrouter.complete) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--date", required=True)
    ap.add_argument("--source", choices=["dispatch", "local"], default="local")
    ap.add_argument("--dry-run", action="store_true", help="resolve targets and print the estimate; send nothing")
    ap.add_argument("--baseline", default=DEFAULT_BASELINE)
    ap.add_argument("--cap", type=float, default=DEFAULT_CAP)
    ap.add_argument("--instances", type=int, default=5)
    ap.add_argument("--lane-hosts", type=int, default=2)
    ap.add_argument("--no-outside", action="store_true")
    ap.add_argument("--allow-no-night", action="store_true",
                    help="run even when the date has no nightly run record (the nightly cap is then not netted off)")
    ap.add_argument("--out-dir", default=str(OUT_DIR))
    ap.add_argument("--routes-dir", default=str(ROUTES_DIR))
    ap.add_argument("--runs-dir", default=str(RUNS_DIR))
    args = ap.parse_args(argv)

    out = Path(args.out_dir) / args.date
    if (out / "run.json").exists() and not args.dry_run:
        print(f"routine: {args.date} already has a run record; nothing sent")
        return 0

    if not (Path(args.runs_dir) / args.date / "run.json").exists() and not args.allow_no_night:
        print(f"routine: {args.date} has no nightly run record. Run this after the nightly so the two "
              f"together stay under ${BUDGET_USD:.2f}; nothing sent")
        return 2
    billed_tonight = night_billed(args.date, Path(args.runs_dir))
    cap_usd = effective_cap(args.cap, billed_tonight)
    system = overhead()

    baseline = resolve_baseline(args.baseline, model_lister())
    lanes = lane_targets(lister, hosts=max(1, args.lane_hosts), outside=not args.no_outside, routes_dir=Path(args.routes_dir))
    if baseline is None:
        print(f"routine: no model under {BASELINE_PREFIX} is listed and {args.baseline} was not found; stopping before any spend")
        return 2
    if not any(t["kind"] == "lane" for t in lanes):
        print("routine: no lane endpoint is both on the route list and listed with a price; stopping before any spend")
        return 2
    targets = [baseline] + lanes

    instances = max(1, args.instances)
    while True:
        jobs = build_jobs(instances)
        est = sum(call_estimate(system, j, t)[0] for j in jobs for t in targets)
        worst = sum(call_estimate(system, j, t)[1] for j in jobs for t in targets)
        if worst <= cap_usd or instances == 1:
            break
        instances -= 1

    print(f"routine {args.date}: cap ${cap_usd:.2f} (night billed ${billed_tonight:.4f}), "
          f"{len(jobs)} jobs x {len(targets)} targets = {len(jobs) * len(targets)} calls, "
          f"estimate ${est:.4f}, worst case ${worst:.4f}")
    for t in targets:
        print(f"  {t['kind']:8s} {t['slug']} {t['tag'] or '(default routing)'} "
              f"in ${t['price_in'] * 1e6:.3f}/M out ${t['price_out'] * 1e6:.3f}/M")
    if worst > cap_usd:
        print("routine: one instance per job does not fit under the cap; stopping before any spend")
        return 2
    if args.dry_run:
        return 0

    out.mkdir(parents=True, exist_ok=True)
    (out / "system.txt").write_text(system, encoding="utf-8")
    with (out / "jobs.jsonl").open("w", encoding="utf-8") as f:
        for j in jobs:
            f.write(json.dumps(j, ensure_ascii=False) + "\n")
    resp = out / "responses.jsonl"
    if resp.exists():
        resp.unlink()

    run_id = f"routine-{args.date}-{args.source}"
    started = now_iso()
    cap = HardCap(cap_usd)
    rows = send_all(run_id, system, jobs, targets, cap, resp, completer=completer)

    summary = summarise(rows)
    record = {
        "run_id": run_id, "date": args.date, "source": args.source, "started": started, "finished": now_iso(),
        "baseline": baseline, "targets": targets, "instances": instances, "lane_hosts": args.lane_hosts,
        "route_as_of": next((t.get("as_of") for t in lanes), None),
        "overhead_chars": len(system), "calls_per_month": CALLS_PER_MONTH,
        "cap_usd": cap_usd, "night_billed_usd": billed_tonight, "estimate_usd": round(est, 4),
        "total_billed_usd": round(cap.spent, 4),
        "skipped_budget": sum(1 for r in rows if r["status"] == "skipped_budget"),
        "by_status": {s: sum(1 for r in rows if r["status"] == s) for s in sorted({r["status"] for r in rows})},
        "summary": summary,
    }
    (out / "run.json").write_text(json.dumps(record, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    (out / "report.md").write_text(report_md(record, summary, rows), encoding="utf-8")
    print(f"done: {len(rows)} rows, billed ${cap.spent:.4f}, report at {out / 'report.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
