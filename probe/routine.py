def _clean(text: str) -> str:
    return (text or "").replace("*", "").replace("`", "")


def _line(text: str, key: str) -> str | None:
    """Value of the last line that starts with KEY: (case-insensitive), or None."""
    found = re.findall(rf"(?im)^\s*{re.escape(key)}\s*:\s*(.*?)\s*$", _clean(text))
    return found[-1] if found else None


def _idset(text: str, key: str) -> set[str] | None:
    v = _line(text, key)
    if v is None:
        return None
    return set(_ids(v.upper()))


def _number(s: str | None) -> float | None:
    if s is None:
        return None
    m = re.search(r"-?\d+(?:\.\d+)?", s.replace(",", "").replace("$", ""))
    return float(m.group(0)) if m else None


def _name(s: str | None) -> str:
    """First alphabetic word, lower case, so a trailing note after the name does not fail it."""
    m = re.search(r"[A-Za-z]+", s or "")
    return m.group(0).lower() if m else ""


def grade(job: dict[str, Any], text: str) -> dict[str, Any]:
    """Return {"passed", "score", "detail"}; score is the share of answer fields that match."""
    exp = job["expect"]
    name = job["job"]
    checks: list[bool] = []
    if name in ("heartbeat", "monitor"):
        key = "DUE" if name == "heartbeat" else "FLAGGED"
        got = _idset(text, key)
        checks.append(got is not None and got == set(exp[key]))
        detail = f"{key} got {sorted(got) if got is not None else None}"
    elif name == "digest":
        got_a = _idset(text, "ACTION")
        got_t = _number(_line(text, "INVOICE_TOTAL"))
        checks.append(got_a is not None and got_a == set(exp["ACTION"]))
        checks.append(got_t is not None and abs(got_t - float(exp["INVOICE_TOTAL"])) < 0.005)
        detail = f"ACTION got {sorted(got_a) if got_a is not None else None}; INVOICE_TOTAL got {got_t}"
    elif name == "briefing":
        top, old = _line(text, "TOP_REVENUE"), _line(text, "OLDEST")
        tot = _number(_line(text, "TOTAL_HEADCOUNT"))
        checks.append(_name(top) == _name(exp["TOP_REVENUE"]))
        checks.append(_name(old) == _name(exp["OLDEST"]))
        checks.append(tot is not None and int(tot) == int(exp["TOTAL_HEADCOUNT"]))
        detail = f"TOP_REVENUE got {top}; OLDEST got {old}; TOTAL_HEADCOUNT got {tot}"
    elif name == "tagging":
        truth = exp["TAGS"]
        got = {f"K-{n}": lab.upper() for n, lab in re.findall(r"\bK-(\d+)\s*[=:]\s*([A-Za-z]+)", _clean(text))}
        right = sum(1 for k, v in truth.items() if got.get(k) == v)
        score = right / len(truth)
        return {"passed": score >= TAG_PASS, "score": round(score, 4), "detail": f"{right}/{len(truth)} tickets"}
    else:
        raise ValueError(f"unknown job {name}")
    score = sum(checks) / len(checks)
    return {"passed": all(checks), "score": round(score, 4), "detail": detail}


